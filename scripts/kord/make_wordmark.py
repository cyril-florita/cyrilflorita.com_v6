"""
Kord's wordmark: "KORD" in Archivo Expanded Black (Archivo's variable font at wdth 125, wght 900),
pulled 2.2x wide and 0.8x tall (the user's pick, option 12 of the stretched-type sheet).

Writes:
  scripts/kord/fonts/ArchivoExpanded-Black.ttf   static instance (Blender's down-tube wordmark;
                                                 build_bike.py stretches its text the same way)
  components/kord/wordmark.js                    the outlined, stretched path for the site's logo
  public/builds/kord/kord-wordmark.svg            the same as a file

  python3 scripts/kord/make_wordmark.py <Archivo[wdth,wght].ttf>
"""
import os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

SX, SY = 2.2, 0.8
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
vf = TTFont(sys.argv[1])
font = instantiateVariableFont(vf, {"wdth": 125, "wght": 900})
font["name"].setName("Archivo Expanded Black", 1, 3, 1, 0x409)
font["name"].setName("Archivo Expanded Black", 4, 3, 1, 0x409)
os.makedirs(os.path.join(here, "fonts"), exist_ok=True)
font.save(os.path.join(here, "fonts", "ArchivoExpanded-Black.ttf"))

gs = font.getGlyphSet(); cmap = font.getBestCmap(); hmtx = font["hmtx"]
cap = font["OS/2"].sCapHeight
# pair kerning from GPOS isn't applied (KO, OR, RD barely kern in Archivo); advances only
pen = SVGPathPen(gs)
x = 0
for ch in "KORD":
    g = cmap[ord(ch)]
    # font units, y up -> SVG, y down, with the stretch: (x, y) -> (SX * (x + pen_x), SY * (cap - y))
    gs[g].draw(TransformPen(pen, (SX, 0, 0, -SY, SX * x, SY * cap)))
    x += hmtx[g][0]
# trim the last glyph's right side bearing so the box ends at the D
last = cmap[ord("D")]
xmax = SX * (x - hmtx[last][0] + gs[last].width - (hmtx[last][0] - font["glyf"][last].xMax))
lsb = SX * font["glyf"][cmap[ord("K")]].xMin
w, h = xmax - lsb, SY * cap
d = pen.getCommands()
vb = f"{lsb:.1f} 0 {w:.1f} {h:.1f}"
open(os.path.join(root, "components", "kord", "wordmark.js"), "w").write(
    "// Generated by scripts/kord/make_wordmark.py: \"KORD\" in Archivo Expanded Black, outlined and\n"
    "// stretched 2.2x wide and 0.8x tall. Don't edit by hand; re-run the script.\n"
    f"export const WORDMARK = {{ viewBox: \"{vb}\", ratio: {w / h:.4f}, d: \"{d}\" }};\n")
open(os.path.join(root, "public", "pitch", "kord", "kord-wordmark.svg"), "w").write(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}"><title>Kord</title><path fill="#fff" d="{d}"/></svg>\n')
print("viewBox", vb, "ratio", round(w / h, 3), "path chars", len(d))
