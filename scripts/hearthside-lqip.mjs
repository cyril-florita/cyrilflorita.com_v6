// Tiny blurred previews for Hearthside's photos: each photo's 900w export
// (or the hero's 1400w) shrunk to 24px wide and blurred, as a WebP data URI.
// <Photo> and the Home hero paint it as the frame's background, so a soft
// preview shows while the real image loads (no grey boxes, no JS).
// Re-run after adding or replacing a photo: node scripts/hearthside-lqip.mjs
import sharp from "sharp";
import { readdirSync, writeFileSync } from "node:fs";

const DIR = "public/img/hearthside/photos";
const OUT = "components/hearthside/photo-lqip.js";

const bases = [...new Set(readdirSync(DIR).filter((f) => f.endsWith(".webp")).map((f) => f.replace(/-\d+\.webp$/, "")))].sort();
const map = {};
for (const base of bases) {
  const file = readdirSync(DIR).filter((f) => f.startsWith(`${base}-`) && f.endsWith(".webp")).sort((a, b) => parseInt(a.match(/-(\d+)\.webp$/)[1]) - parseInt(b.match(/-(\d+)\.webp$/)[1]))[0];
  const buf = await sharp(`${DIR}/${file}`).resize(24).blur(0.6).webp({ quality: 50 }).toBuffer();
  map[`/img/hearthside/photos/${base}`] = `data:image/webp;base64,${buf.toString("base64")}`;
}

writeFileSync(OUT, `// Generated by scripts/hearthside-lqip.mjs: a tiny blurred preview of each\n// photo (keyed by its base path), painted behind the real image while it loads.\nexport const PHOTO_LQIP = ${JSON.stringify(map, null, 2)};\n`);
console.log(Object.keys(map).length, "previews,", JSON.stringify(map).length, "bytes");
